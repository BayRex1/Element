private enum class ProfileLinkBrand {
    Element,
    Telegram,
    YouTube,
    TikTok,
    Steam,
    GitHub,
    Vk,
    Spotify,
    DonationAlerts,
    Discord,
    Pinterest,
    KConnect,
    Onion,
    Site
}

@Composable
internal fun ProfileLinkIcon(
    link: String,
    modifier: Modifier = Modifier,
    size: Dp = 19.dp
) {
    val brand = remember(link) { resolveProfileLinkBrand(link) }
    val neutralColorHex = ElementUiPalette.TextSecondary.toSvgHex()
    val svg = remember(brand, neutralColorHex) {
        when (brand) {
            ProfileLinkBrand.Element -> elementLinkSvg(neutralColorHex)
            ProfileLinkBrand.Telegram -> TELEGRAM_SVG
            ProfileLinkBrand.YouTube -> YOUTUBE_SVG
            ProfileLinkBrand.TikTok -> TIKTOK_SVG
            ProfileLinkBrand.Steam -> STEAM_SVG
            ProfileLinkBrand.GitHub -> githubLinkSvg(neutralColorHex)
            ProfileLinkBrand.Vk -> VK_SVG
            ProfileLinkBrand.Spotify -> SPOTIFY_SVG
            ProfileLinkBrand.DonationAlerts -> DONATION_ALERTS_SVG
            ProfileLinkBrand.Discord -> DISCORD_SVG
            ProfileLinkBrand.Pinterest -> PINTEREST_SVG
            ProfileLinkBrand.KConnect -> KCONNECT_SVG
            ProfileLinkBrand.Onion -> ONION_SVG
            ProfileLinkBrand.Site -> siteLinkSvg(neutralColorHex)
        }
    }

    ElementSvgImage(
        svg = svg,
        width = size,
        height = size,
        modifier = modifier
    )
}

internal fun normalizeProfileLinkTarget(link: String): String {
    return if (link.startsWith("http://", ignoreCase = true) || link.startsWith("https://", ignoreCase = true)) {
        link
    } else {
        "https://$link"
    }
}

private fun resolveProfileLinkBrand(link: String): ProfileLinkBrand {
    val host = runCatching {
        java.net.URI(normalizeProfileLinkTarget(link))
            .host
            ?.lowercase(Locale.ROOT)
            ?.removePrefix("www.")
    }.getOrNull() ?: return ProfileLinkBrand.Site

    return when {
        host.endsWith(".onion") -> ProfileLinkBrand.Onion
        host == "elemsocial.com" || host.endsWith(".elemsocial.com") -> ProfileLinkBrand.Element
        host == "t.me" || host.endsWith(".t.me") || host == "telegram.me" || host.endsWith(".telegram.me") ->
            ProfileLinkBrand.Telegram
        host == "youtube.com" || host.endsWith(".youtube.com") || host == "youtu.be" ->
            ProfileLinkBrand.YouTube
        host == "tiktok.com" || host.endsWith(".tiktok.com") ->
            ProfileLinkBrand.TikTok
        host == "steamcommunity.com" || host.endsWith(".steamcommunity.com") || host == "store.steampowered.com" ->
            ProfileLinkBrand.Steam
        host == "github.com" || host.endsWith(".github.com") ->
            ProfileLinkBrand.GitHub
        host == "vk.com" || host.endsWith(".vk.com") ->
            ProfileLinkBrand.Vk
        host == "open.spotify.com" || host.endsWith(".spotify.com") ->
            ProfileLinkBrand.Spotify
        host == "donationalerts.com" || host.endsWith(".donationalerts.com") ->
            ProfileLinkBrand.DonationAlerts
        host == "discord.com" || host.endsWith(".discord.com") || host == "discord.gg" || host.endsWith(".discord.gg") ->
            ProfileLinkBrand.Discord
        host == "pinterest.com" || host.endsWith(".pinterest.com") || host == "pin.it" ->
            ProfileLinkBrand.Pinterest
        host == "k-connect.ru" || host.endsWith(".k-connect.ru") ->
            ProfileLinkBrand.KConnect
        else -> ProfileLinkBrand.Site
    }
}

